//! Explicit identity/default origins keep server expressions out of literal editors.
use super::*;
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum Generation {
    #[default]
    None,
    Serial,
    Always,
    ByDefault,
    ByDefaultOnNull,
}
pub(super) fn postgres_integer(data_type: &str) -> bool {
    [
        "INT2",
        "INT4",
        "INT8",
        "SMALLINT",
        "INTEGER",
        "INT",
        "BIGINT",
        "SERIAL",
        "BIGSERIAL",
        "SMALLSERIAL",
    ]
    .contains(&data_type.to_ascii_uppercase().as_str())
}
impl Column {
    pub(super) fn computed_clause(
        &self,
        dialect: Dialect,
        backslash: bool,
    ) -> Result<Option<String>> {
        let Some(computed) = &self.computed else {
            return Ok(None);
        };
        ensure!(
            !self.auto_increment && self.default_value.is_empty(),
            "生成列不能同时设置自动递增或默认值"
        );
        expression(&computed.expression, backslash)?;
        ensure!(!matches!(dialect, Dialect::Hive), "Hive 不支持生成列");
        Ok(Some(format!(
            " GENERATED ALWAYS AS ({}) {}",
            computed.expression,
            if computed.stored && !matches!(dialect, Dialect::Oracle) {
                "STORED"
            } else {
                "VIRTUAL"
            }
        )))
    }
    pub(super) fn identity_clause(&self, dialect: Dialect) -> Result<Option<&'static str>> {
        if !self.auto_increment || !matches!(dialect, Dialect::Postgres | Dialect::Oracle) {
            return Ok(None);
        }
        ensure!(
            self.default_value.is_empty() || self.generation != Generation::None,
            "自动递增列不能同时指定默认值"
        );
        if matches!(dialect, Dialect::Postgres) {
            ensure!(
                self.default_value.is_empty()
                    || self.generation == Generation::Serial
                        && self.default_value.starts_with("nextval("),
                "标识列不能同时指定默认值"
            );
            ensure!(
                postgres_integer(&self.data_type),
                "PostgreSQL 自动递增需要 smallint、integer 或 bigint 类型"
            );
            ensure!(
                self.generation != Generation::ByDefaultOnNull,
                "PostgreSQL 不支持 ON NULL 标识列"
            );
            if ["SERIAL", "BIGSERIAL", "SMALLSERIAL"]
                .contains(&self.data_type.to_ascii_uppercase().as_str())
            {
                return Ok(None);
            }
        } else {
            ensure!(
                ["NUMBER", "INTEGER", "INT", "SMALLINT", "DECIMAL", "NUMERIC"]
                    .contains(&self.data_type.to_ascii_uppercase().as_str()),
                "Oracle 标识列需要数值类型"
            );
        }
        Ok(Some(match self.generation {
            Generation::Always => " GENERATED ALWAYS AS IDENTITY",
            Generation::ByDefaultOnNull => " GENERATED BY DEFAULT ON NULL AS IDENTITY",
            _ => " GENERATED BY DEFAULT AS IDENTITY",
        }))
    }
    pub(super) fn default_sql(&self, dialect: Dialect, backslash: bool) -> Result<Option<String>> {
        if self.default_value.is_empty()
            || self.auto_increment && matches!(dialect, Dialect::Postgres | Dialect::Oracle)
            || self.generation == Generation::Serial && self.default_value.starts_with("nextval(")
        {
            return Ok(None);
        }
        if self.default_expression {
            expression(&self.default_value, backslash)?;
            let mut value = self.default_value.clone();
            if matches!(dialect, Dialect::Mysql)
                && !value.starts_with('(')
                && !value.to_ascii_uppercase().starts_with("CURRENT_TIMESTAMP")
            {
                value = format!("({value})");
            }
            Ok(Some(value))
        } else if self.default_value.eq_ignore_ascii_case("NULL")
            || self.default_value.eq_ignore_ascii_case("CURRENT_TIMESTAMP")
        {
            Ok(Some(self.default_value.to_ascii_uppercase()))
        } else {
            Ok(Some(literal(&self.default_value, backslash)))
        }
    }
}
fn expression(value: &str, backslash: bool) -> Result<()> {
    let tokens = mysql_definition::tokens(value, backslash)?;
    ensure!(
        !tokens.is_empty()
            && tokens
                .iter()
                .all(|t| !matches!(&value[t.range.clone()], "," | ")" | ";")),
        "表达式不能包含其他语句或字段"
    );
    Ok(())
}
pub(super) fn postgres_enable(
    table: &str,
    column: &Column,
    backslash: bool,
) -> Result<Vec<String>> {
    let name = Dialect::Postgres.quote(&column.name)?;
    let clause = column.identity_clause(Dialect::Postgres)?.ok_or_else(|| {
        anyhow::anyhow!("已有字段启用自动递增时请使用整数类型，而不是 SERIAL 伪类型")
    })?;
    let table_literal = literal(table, backslash);
    let column_literal = literal(&column.name, backslash);
    Ok(vec![
        format!("ALTER TABLE {table} ALTER COLUMN {name} ADD{}", clause),
        format!(
            "SELECT setval(s.oid::regclass,GREATEST(COALESCE((SELECT MAX({name})::bigint FROM {table}),0),0)+1,false) FROM pg_class s JOIN pg_depend d ON d.objid=s.oid AND d.classid='pg_class'::regclass JOIN pg_attribute a ON a.attrelid=d.refobjid AND a.attnum=d.refobjsubid WHERE d.refobjid={table_literal}::regclass AND d.refclassid='pg_class'::regclass AND d.deptype='i' AND a.attname={column_literal} AND s.relkind='S'"
        ),
    ])
}
