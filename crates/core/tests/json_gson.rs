use anyhow::Result;
use serde::Deserialize;
use tomato_core::tools::json_transform;

#[derive(Debug, Deserialize, PartialEq, Eq)]
struct Case {
    input: String,
    compact: Option<String>,
    pretty: Option<String>,
    #[serde(default)]
    error: bool,
}

#[test]
#[ignore = "Set TOMATO_ORACLE_GSON_JAR to the original Gson 2.11.0 jar; compiles a read-only Java oracle in a temporary directory"]
fn live_original_gson_reproduces_the_complete_golden_corpus() -> Result<()> {
    use std::{
        io::Write,
        path::PathBuf,
        process::{Command, Stdio},
    };
    let root = tempfile::tempdir()?;
    let jar = std::env::var_os("TOMATO_ORACLE_GSON_JAR")
        .map(PathBuf::from)
        .ok_or_else(|| anyhow::anyhow!("set TOMATO_ORACLE_GSON_JAR"))?;
    let executable = |name: &str| {
        let name = if cfg!(windows) {
            format!("{name}.exe")
        } else {
            name.to_owned()
        };
        std::env::var_os("TOMATO_ORACLE_JDK")
            .map(PathBuf::from)
            .map_or_else(|| PathBuf::from(&name), |p| p.join("bin").join(&name))
    };
    let source =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/java/JsonLenientOracle.java");
    let compile = Command::new(executable("javac"))
        .arg("-encoding")
        .arg("UTF-8")
        .arg("-cp")
        .arg(&jar)
        .arg("-d")
        .arg(root.path())
        .arg(source)
        .output()?;
    anyhow::ensure!(
        compile.status.success(),
        "Java oracle compilation failed: {}",
        String::from_utf8_lossy(&compile.stderr)
    );
    let corpus: Vec<Case> = include_str!("fixtures/gson-2.11-lenient.jsonl")
        .lines()
        .map(serde_json::from_str)
        .collect::<std::result::Result<_, _>>()?;
    let input = root.path().join("inputs.jsonl");
    let mut file = std::fs::File::create(&input)?;
    for case in &corpus {
        writeln!(file, "{}", serde_json::to_string(&case.input)?)?;
    }
    drop(file);
    let classpath = std::env::join_paths([root.path(), jar.as_path()])?;
    let result = Command::new(executable("java"))
        .arg("-cp")
        .arg(classpath)
        .arg("JsonLenientOracle")
        .stdin(Stdio::from(std::fs::File::open(input)?))
        .output()?;
    anyhow::ensure!(
        result.status.success(),
        "Java oracle failed: {}",
        String::from_utf8_lossy(&result.stderr)
    );
    let actual: Vec<Case> = std::str::from_utf8(&result.stdout)?
        .lines()
        .map(serde_json::from_str)
        .collect::<std::result::Result<_, _>>()?;
    assert_eq!(actual, corpus);
    Ok(())
}

#[test]
fn original_gson_211_lenient_grammar_and_writing_golden() -> Result<()> {
    // Generated by the original application's Gson 2.11.0 dependency, using
    // JsonParser.parseString + its unchanged default/pretty Gson writers.
    for (index, line) in include_str!("fixtures/gson-2.11-lenient.jsonl")
        .lines()
        .enumerate()
    {
        let case: Case = serde_json::from_str(line)?;
        for (action, expected) in [("format", case.pretty), ("minify", case.compact)] {
            let result = json_transform(&case.input, action);
            if case.error {
                assert!(
                    result.is_err(),
                    "case {index} {action}: accepted {:?}",
                    case.input
                );
            } else {
                assert_eq!(
                    result.ok(),
                    expected,
                    "case {index} {action}: {:?}",
                    case.input
                );
            }
        }
    }
    Ok(())
}

#[test]
fn deeply_nested_and_oversized_documents_fail_without_unbounded_buffers() {
    let deep = format!("{}0{}", "[".repeat(130), "]".repeat(130));
    assert!(json_transform(&deep, "format").is_err());
    let huge = "x".repeat(8 * 1024 * 1024 + 1);
    assert!(json_transform(&huge, "format").is_err());
    // Do not silently replace malformed UTF-16 and merge distinct object keys.
    for text in [r#""\uD800""#, r#""\uDC00""#, r#"{"\uD800":1,"\uDC00":2}"#] {
        assert!(json_transform(text, "format").is_err());
    }
    let many = format!("[{}]", "0,".repeat(250_000));
    assert!(json_transform(&many, "minify").is_err());
    let expanded = format!(
        "{}{}{}",
        "[".repeat(120),
        "0,".repeat(160_000),
        "]".repeat(120)
    );
    assert!(json_transform(&expanded, "format").is_err());
    assert!(json_transform(&expanded, "minify").is_ok());
}
