//! Cross-server PostgreSQL CREATE uses catalog expressions, identities and constraints.
use super::*;
pub(super) async fn create(
    session: &mut AnyConnection,
    source: &TableId,
    target: &TableId,
) -> Result<Vec<String>> {
    let values = [
        Cell::Text(source.schema.clone()),
        Cell::Text(source.name.clone()),
    ];
    let rows=workbench::metadata(session,"SELECT quote_ident(a.attname),format_type(a.atttypid,a.atttypmod),a.attnotnull::text,a.attidentity::text,a.attgenerated::text,COALESCE(pg_get_expr(d.adbin,d.adrelid),''),COALESCE(quote_literal(col_description(c.oid,a.attnum)),''),a.attname::text FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid JOIN pg_namespace n ON n.oid=c.relnamespace LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum WHERE n.nspname=$1 AND c.relname=$2 AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum",&values).await?;
    let qualified = workbench::plan::qualified("POSTGRESQL", target)?;
    let mut columns = Vec::new();
    let mut comments = Vec::new();
    let mut bytes = 0usize;
    for row in rows {
        let cells = (0..row.len())
            .map(|i| workbench::text(&row, i))
            .collect::<Result<Vec<_>>>()?;
        bytes += cells.iter().map(String::len).sum::<usize>();
        ensure!(bytes <= BUDGET, "PostgreSQL表定义超过8 MiB");
        let mut column = format!("{} {}", cells[0], cells[1]);
        if cells[4] == "s" {
            column.push_str(&format!(" GENERATED ALWAYS AS ({}) STORED", cells[5]));
        } else if !cells[3].is_empty() || cells[5].starts_with("nextval(") {
            column.push_str(if cells[3] == "a" {
                " GENERATED ALWAYS AS IDENTITY"
            } else {
                " GENERATED BY DEFAULT AS IDENTITY"
            });
            let parameters=workbench::metadata(session,"SELECT s.seqstart::text,s.seqincrement::text,s.seqmin::text,s.seqmax::text,s.seqcache::text,s.seqcycle::text FROM pg_sequence s WHERE s.seqrelid=pg_get_serial_sequence($1,$2)::regclass",&[Cell::Text(workbench::plan::qualified("POSTGRESQL",source)?),Cell::Text(cells[7].clone())]).await?;
            if let Some(row) = parameters.first() {
                let values = (0..6)
                    .map(|i| workbench::text(row, i))
                    .collect::<Result<Vec<_>>>()?;
                column.push_str(&format!(
                    " (START WITH {} INCREMENT BY {} MINVALUE {} MAXVALUE {} CACHE {} {})",
                    values[0],
                    values[1],
                    values[2],
                    values[3],
                    values[4],
                    if values[5] == "true" || values[5] == "t" {
                        "CYCLE"
                    } else {
                        "NO CYCLE"
                    }
                ));
            }
        } else if !cells[5].is_empty() {
            column.push_str(&format!(" DEFAULT {}", cells[5]));
        }
        if cells[2] == "true" || cells[2] == "t" {
            column.push_str(" NOT NULL");
        }
        columns.push(column);
        if !cells[6].is_empty() {
            comments.push(format!(
                "COMMENT ON COLUMN {qualified}.{} IS {}",
                cells[0], cells[6]
            ));
        }
    }
    // LIKE INCLUDING ALL does not reproduce foreign keys; retain its original semantics.
    for row in workbench::metadata(session,"SELECT quote_ident(con.conname),pg_get_constraintdef(con.oid,true) FROM pg_constraint con JOIN pg_class c ON c.oid=con.conrelid JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=$1 AND c.relname=$2 AND con.contype IN ('p','u','c') ORDER BY con.conname",&values).await?{
        columns.push(format!("CONSTRAINT {} {}",workbench::text(&row,0)?,workbench::text(&row,1)?));
    }
    let mut result = vec![format!(
        "CREATE TABLE {qualified} (\n{}\n)",
        columns.join(",\n")
    )];
    result.extend(comments);
    if let Some(row)=workbench::metadata(session,"SELECT quote_literal(obj_description(c.oid)) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=$1 AND c.relname=$2",&values).await?.first() && let Some(comment)=workbench::optional(row,0)? {result.push(format!("COMMENT ON TABLE {qualified} IS {comment}"));}
    // Non-constraint index definitions contain executable expressions from pg_catalog.
    for row in workbench::metadata(session,"SELECT pg_get_indexdef(i.indexrelid),quote_ident(ci.relname) FROM pg_index i JOIN pg_class c ON c.oid=i.indrelid JOIN pg_namespace n ON n.oid=c.relnamespace JOIN pg_class ci ON ci.oid=i.indexrelid WHERE n.nspname=$1 AND c.relname=$2 AND NOT EXISTS(SELECT 1 FROM pg_constraint con WHERE con.conindid=i.indexrelid) ORDER BY ci.relname",&values).await?{
        let sql=workbench::text(&row,0)?;
        let tokens=tomato_core::table_design::mysql_definition::tokens(&sql,false)?;
        let on=tokens.iter().position(|t|sql[t.range.clone()].eq_ignore_ascii_case("ON")).context("索引定义缺少ON")?;
        let using=tokens.iter().skip(on+1).find(|t|sql[t.range.clone()].eq_ignore_ascii_case("USING")).context("索引定义缺少USING")?;
        let name=workbench::text(&row,1)?;
        let prefix=if sql.starts_with("CREATE UNIQUE"){"CREATE UNIQUE INDEX"}else{"CREATE INDEX"};
        result.push(format!("{prefix} {name} ON {qualified} {}",&sql[using.range.start..]));
    }
    ensure!(
        result.iter().map(String::len).sum::<usize>() <= BUDGET,
        "PostgreSQL表定义超过8 MiB"
    );
    Ok(result)
}

pub(super) async fn reset_identity(
    session: &mut AnyConnection,
    definition: &tomato_core::workbench::TableDefinition,
) -> Result<()> {
    let qualified = workbench::plan::qualified("POSTGRESQL", &definition.table)?;
    for column in definition.columns.iter().filter(|c| c.auto_increment) {
        let parameters=workbench::metadata(session,"SELECT n.nspname::text,c.relname::text,s.seqstart::text,s.seqincrement::text,s.seqmin::text,s.seqmax::text FROM pg_sequence s JOIN pg_class c ON c.oid=s.seqrelid JOIN pg_namespace n ON n.oid=c.relnamespace WHERE s.seqrelid=pg_get_serial_sequence($1,$2)::regclass",&[Cell::Text(qualified.clone()),Cell::Text(column.name.clone())]).await?;
        let Some(row) = parameters.first() else {
            continue;
        };
        let sequence = workbench::plan::qualified(
            "POSTGRESQL",
            &TableId {
                schema: workbench::text(row, 0)?,
                name: workbench::text(row, 1)?,
            },
        )?;
        let start = workbench::text(row, 2)?.parse::<i64>()?;
        let increment = workbench::text(row, 3)?.parse::<i64>()?;
        let min = workbench::text(row, 4)?.parse::<i64>()?;
        let max = workbench::text(row, 5)?.parse::<i64>()?;
        let last = workbench::metadata(
            session,
            &format!("SELECT last_value::text,is_called::text FROM {sequence}"),
            &[],
        )
        .await?;
        let row = last.first().context("自增序列不存在")?;
        let current = workbench::text(row, 0)?.parse::<i64>()?;
        let called = matches!(workbench::text(row, 1)?.as_str(), "t" | "true");
        let quoted = crate::dialect::resolve("POSTGRESQL")?.quote(&column.name)?;
        let extreme = if increment > 0 { "MAX" } else { "MIN" };
        let rows = workbench::metadata(
            session,
            &format!("SELECT {extreme}({quoted})::text FROM {qualified}"),
            &[],
        )
        .await?;
        let Some(value) = rows
            .first()
            .map(|r| workbench::optional(r, 0))
            .transpose()?
            .flatten()
        else {
            continue;
        };
        let value = value.parse::<i64>()?;
        let candidate = if increment > 0 {
            value.max(current).max(start)
        } else {
            value.min(current).min(start)
        }
        .clamp(min, max);
        let called = called
            || if increment > 0 {
                value >= start
            } else {
                value <= start
            };
        sqlx::query("SELECT setval($1::regclass,$2,$3)")
            .bind(&sequence)
            .bind(candidate)
            .bind(called)
            .execute(&mut *session)
            .await
            .context("数据已提交，但更新自增序列失败")?;
    }
    Ok(())
}
