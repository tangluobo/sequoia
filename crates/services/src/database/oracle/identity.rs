//! Preserve explicit identity values and restore the original generation mode.
use super::super::workbench;
use anyhow::{Context, Result, ensure};
use sqlx::{AnyConnection, Executor as _};
use tomato_core::workbench::{Cell, TableId};
pub(in crate::database) struct Identity {
    qualified: String,
    columns: Vec<Column>,
}
struct Column {
    quoted: String,
    mode: String,
    changed: bool,
}
impl Identity {
    pub(in crate::database) async fn prepare(
        conn: &mut AnyConnection,
        table: &TableId,
    ) -> Result<Self> {
        let rows=workbench::metadata(conn,"SELECT column_name,generation_type FROM all_tab_identity_cols WHERE owner=:1 AND table_name=:2 ORDER BY column_name",&[Cell::Text(table.schema.clone()),Cell::Text(table.name.clone())]).await?;
        let qualified = workbench::plan::qualified("ORACLE", table)?;
        let quote = crate::dialect::resolve("ORACLE")?;
        // Validate every identifier before changing the first column.
        let mut columns = Vec::with_capacity(rows.len());
        for row in rows {
            let mode = workbench::text(&row, 1)?.to_ascii_uppercase();
            ensure!(
                ["ALWAYS", "BY DEFAULT", "BY DEFAULT ON NULL"].contains(&mode.as_str()),
                "Oracle 标识列模式无效"
            );
            columns.push(Column {
                quoted: quote.quote(&workbench::text(&row, 0)?)?,
                mode,
                changed: false,
            });
        }
        let mut state = Self { qualified, columns };
        let mut failure = None;
        for column in &mut state.columns {
            if column.mode == "ALWAYS" {
                match conn
                    .execute(
                        format!(
                            "ALTER TABLE {} MODIFY ({} GENERATED BY DEFAULT AS IDENTITY)",
                            state.qualified, column.quoted
                        )
                        .as_str(),
                    )
                    .await
                {
                    Ok(_) => column.changed = true,
                    Err(error) => {
                        failure = Some(error);
                        break;
                    }
                }
            }
        }
        if let Some(error) = failure {
            return match state.finish(conn, false).await {
                Ok(()) => Err(error.into()),
                Err(cleanup) => {
                    Err(error).context(format!("恢复 Oracle 标识列模式失败：{cleanup}"))
                }
            };
        }
        Ok(state)
    }
    pub(in crate::database) async fn finish(
        self,
        conn: &mut AnyConnection,
        reset: bool,
    ) -> Result<()> {
        let mut failure = None;
        for column in self.columns {
            if (column.changed || reset)
                && let Err(error) = conn
                    .execute(
                        format!(
                            "ALTER TABLE {} MODIFY ({} GENERATED {} AS IDENTITY{})",
                            self.qualified,
                            column.quoted,
                            column.mode,
                            if reset {
                                " (START WITH LIMIT VALUE)"
                            } else {
                                ""
                            }
                        )
                        .as_str(),
                    )
                    .await
                && failure.is_none()
            {
                // Attempt every remaining column even if one ALTER fails.
                failure = Some(error);
            }
        }
        if let Some(error) = failure {
            return Err(error)
                .context("恢复 Oracle 标识列模式或序列失败，请核对已传输数据和表结构");
        }
        Ok(())
    }
}
