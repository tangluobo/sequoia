//! Stored-program execution and generated/default column behavior against owned engines.
use super::designer_tests::{edit, load, save};
use super::*;
pub(super) async fn run(db: &mut Databases, c: &Connection, kind: &str, scope: &str) -> Result<()> {
    let dialect = tomato_services::dialect::resolve(kind)?;
    let q = |s: &str| dialect.quote(s);
    let table = format!("{}.{}", q(scope)?, q("program_rows")?);
    let trigger = format!("{}.{}", q(scope)?, q("program_trigger")?);
    let function = format!("{}.{}", q(scope)?, q("program_function")?);
    db.query(
        c,
        &format!("CREATE TABLE {table}(id INTEGER PRIMARY KEY,value INTEGER)"),
    )
    .await?;
    let program = if kind == "MYSQL" {
        format!(
            "DELIMITER //\nCREATE TRIGGER {trigger} BEFORE INSERT ON {table} FOR EACH ROW BEGIN IF NEW.value<0 THEN SET NEW.value=CASE WHEN NEW.value=-1 THEN 1 ELSE 2 END; END IF; END//\nDELIMITER ;\nINSERT INTO {table} VALUES(1,-1); SELECT value FROM {table};"
        )
    } else {
        format!(
            "CREATE FUNCTION {function}() RETURNS trigger LANGUAGE plpgsql AS $body$ BEGIN NEW.value := CASE WHEN NEW.value<0 THEN 1 ELSE 2 END; RETURN NEW; END $body$;CREATE TRIGGER {} BEFORE INSERT ON {table} FOR EACH ROW EXECUTE FUNCTION {function}();INSERT INTO {table} VALUES(1,-1); SELECT value FROM {table};",
            q("program_trigger")?
        )
    };
    let run = db
        .script(c, program, tomato_services::database::script::Mode::Run)
        .await?;
    assert_eq!(run.fail_count, 0, "{}", run.info());
    assert_eq!(run.success_count, if kind == "MYSQL" { 3 } else { 4 });
    let result = run
        .statements
        .iter()
        .rev()
        .find(|s| s.success && s.select)
        .and_then(|s| s.result)
        .unwrap();
    assert_eq!(run.results[result].value(0, 0), Some("1"));
    // Lexing follows both the initial session mode and explicit SET changes within a batch.
    let mode_script = if kind == "MYSQL" {
        r"SET SESSION sql_mode='NO_BACKSLASH_ESCAPES';SELECT 'C:\';SET SESSION sql_mode='';SELECT 'it\'s;ok';"
    } else {
        r"SET standard_conforming_strings=off;SELECT 'it\'s;ok';SET standard_conforming_strings=on;SELECT 'C:\';"
    };
    let mixed = db
        .script(
            c,
            mode_script.into(),
            tomato_services::database::script::Mode::Run,
        )
        .await?;
    assert_eq!(mixed.fail_count, 0, "{}", mixed.info());
    assert_eq!(mixed.success_count, 4);
    let values = mixed
        .statements
        .iter()
        .filter(|s| s.select)
        .map(|s| mixed.results[s.result.unwrap()].value(0, 0))
        .collect::<Vec<_>>();
    assert_eq!(
        values,
        if kind == "MYSQL" {
            vec![Some("C:\\"), Some("it's;ok")]
        } else {
            vec![Some("it's;ok"), Some("C:\\")]
        }
    );
    if kind != "POSTGRESQL" {
        return Ok(());
    }

    for (name, definition) in [
        (
            "identity_toggle",
            "INTEGER GENERATED BY DEFAULT AS IDENTITY",
        ),
        ("serial_toggle", "SERIAL"),
    ] {
        let table_id = TableId {
            schema: scope.into(),
            name: name.into(),
        };
        let qualified = format!("{}.{}", q(scope)?, q(name)?);
        db.query(c,&format!("CREATE TABLE {qualified}(id {definition} PRIMARY KEY,note VARCHAR(50));INSERT INTO {qualified}(id,note) VALUES(1000,'explicit')")).await?;
        let snapshot = load(db, c, &table_id).await?;
        assert!(snapshot.definition.columns[0].auto_increment);
        let mut off = edit(snapshot);
        off.after.columns[0].auto_increment = false;
        let disabled = save(db, c, off).await?;
        assert!(!disabled.definition.columns[0].auto_increment);
        assert!(
            db.query(
                c,
                &format!("INSERT INTO {qualified}(note) VALUES('must fail')")
            )
            .await
            .is_err()
        );
        let mut on = edit(disabled);
        on.after.columns[0].auto_increment = true;
        let enabled = save(db, c, on).await?;
        assert!(enabled.definition.columns[0].auto_increment);
        db.query(
            c,
            &format!("INSERT INTO {qualified}(note) VALUES('generated')"),
        )
        .await?;
        let rows = db
            .query(
                c,
                &format!("SELECT id FROM {qualified} WHERE note='generated'"),
            )
            .await?;
        assert_eq!(rows[0].rows[0][0], "1001");
    }
    let original = TableId {
        schema: scope.into(),
        name: "generated_original".into(),
    };
    let original_sql = format!("{}.{}", q(scope)?, q(&original.name)?);
    db.query(c,&format!("CREATE TABLE {original_sql}(id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,amount INTEGER DEFAULT 7,note VARCHAR(50) DEFAULT 'plain',calculated INTEGER GENERATED ALWAYS AS(amount+1) STORED)")).await?;
    let snapshot = load(db, c, &original).await?;
    let mut request = snapshot.definition;
    assert_eq!(
        request.columns[0].generation,
        tomato_core::table_design::Generation::Always
    );
    assert!(request.columns[3].computed.is_some());
    request.table.name = "generated_copy".into();
    db.workbench(c, DatabaseAction::CreateTable { request })
        .await?;
    let copy = format!("{}.{}", q(scope)?, q("generated_copy")?);
    db.query(c, &format!("INSERT INTO {copy}(amount) VALUES(8)"))
        .await?;
    let values = db
        .query(c, &format!("SELECT id,note,calculated FROM {copy}"))
        .await?;
    assert_eq!(values[0].rows[0], ["1", "plain", "9"]);
    assert!(
        db.query(c, &format!("INSERT INTO {copy}(id) VALUES(99)"))
            .await
            .is_err(),
        "ALWAYS identity mode must remain ALWAYS"
    );
    Ok(())
}
