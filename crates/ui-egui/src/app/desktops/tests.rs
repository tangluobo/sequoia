use super::*;
use std::time::{Duration, Instant};

#[test]
fn vnc_password_modal_cancels_or_resumes_the_same_socket_and_respects_save_choice()
-> anyhow::Result<()> {
    use egui::{Event, Key, Modifiers, PointerButton};
    use tokio::io::{AsyncReadExt, AsyncWriteExt};
    use tomato_services::remote_desktop::Status;

    let ctx = egui::Context::default();
    let directory = tempfile::tempdir()?;
    let config = directory.path().join("connections.json");
    let runtime = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(2)
        .enable_all()
        .build()?;
    let listener = runtime.block_on(tokio::net::TcpListener::bind("127.0.0.1:0"))?;
    let mut connection = Connection::new("VNC");
    connection.set("port", listener.local_addr()?.port());
    connection.set("futureLegacy", serde_json::json!({"preserved":true}));
    Store {
        connections: vec![connection.clone()],
        ..Default::default()
    }
    .save(&config)?;
    let original = std::fs::read(&config)?;
    enum Peer {
        ChallengeSent,
        Cancelled,
        FirstFrameRequested,
    }
    let (peer, checkpoints) = std::sync::mpsc::channel();
    let server = runtime.spawn(async move {
        for cancel in [true, false, false] {
            let (mut socket, _) = listener.accept().await?;
            socket.write_all(b"RFB 003.008\n").await?;
            let mut banner = [0; 12];
            socket.read_exact(&mut banner).await?;
            assert_eq!(&banner, b"RFB 003.008\n");
            socket.write_all(&[1, 2]).await?;
            assert_eq!(socket.read_u8().await?, 2);
            socket
                .write_all(&std::array::from_fn::<_, 16, _>(|index| index as u8))
                .await?;
            peer.send(Peer::ChallengeSent)?;
            let mut response = [0; 16];
            if cancel {
                assert!(socket.read_exact(&mut response).await.is_err());
                peer.send(Peer::Cancelled)?;
                continue;
            }
            socket.read_exact(&mut response).await?;
            // Generated by the Java client's DES challenge implementation.
            assert_eq!(
                response,
                [
                    0xb6, 0xcd, 0xfe, 0xac, 0x10, 0xa6, 0xa4, 0x56, 0xb5, 0xd5, 0x3a, 0x16, 0x44,
                    0xa7, 0xa4, 0x75
                ]
            );
            socket.write_u32(0).await?;
            assert_eq!(socket.read_u8().await?, 1);
            socket.write_u16(40).await?;
            socket.write_u16(30).await?;
            socket.write_all(&[0; 16]).await?;
            socket.write_u32(7).await?;
            socket.write_all(b"fixture").await?;
            let mut packet = [0; 46];
            socket.read_exact(&mut packet).await?;
            assert_eq!(packet[36], 3);
            peer.send(Peer::FirstFrameRequested)?;
            // A bounded peer waits for the client's reconnect/close to release the socket.
            let mut input = [0; 128];
            while socket.read(&mut input).await.is_ok_and(|count| count > 0) {}
        }
        Ok::<_, anyhow::Error>(())
    });
    let mut app = TomatoApp::with_repository(&ctx, runtime, ConnectionFileRepository::new(&config));
    app.open_connection(connection);
    let id = app.tabs[0].id.clone();
    let session = |tab: &Tab| -> Status {
        let Panel::NativeDesktop {
            session: Some(session),
            ..
        } = &tab.panel
        else {
            panic!("VNC session was replaced or lost");
        };
        session.status()
    };
    let wait = |app: &TomatoApp, expected| -> anyhow::Result<()> {
        let deadline = Instant::now() + Duration::from_secs(5);
        loop {
            let status = session(&app.tabs[0]);
            if status == expected {
                return Ok(());
            }
            anyhow::ensure!(
                Instant::now() < deadline,
                "waiting for {expected:?}, got {status:?}"
            );
            std::thread::sleep(Duration::from_millis(5));
        }
    };
    let draw = |app: &mut TomatoApp, events| {
        let blocked = app.root_modal_open();
        let mut intent = None;
        let mut output = ctx.run_ui(
            egui::RawInput {
                screen_rect: Some(egui::Rect::from_min_size(
                    egui::Pos2::ZERO,
                    egui::vec2(950., 650.),
                )),
                events,
                ..Default::default()
            },
            |ui| {
                ui.add_enabled_ui(!blocked, |ui| {
                    intent = crate::panels::render_with_connections(
                        ui,
                        &mut app.tabs[0],
                        &mut app.icons,
                        &[],
                    );
                })
                .inner
            },
        );
        output.textures_delta.clear();
        (intent, output)
    };
    let key = |key, pressed| Event::Key {
        key,
        repeat: false,
        pressed,
        physical_key: None,
        modifiers: Modifiers::NONE,
    };
    let peer_checkpoint = || checkpoints.recv_timeout(Duration::from_secs(5));
    for attempt in 0..3 {
        if attempt > 0 {
            app.desktop_menu_action(&id, menu::Action::Reconnect);
        }
        assert!(matches!(peer_checkpoint()?, Peer::ChallengeSent));
        wait(&app, Status::PasswordRequired)?;
        assert!(app.root_modal_open());
        // A key held while a connection opens may deliver repeat events to the modal.
        assert!(
            draw(
                &mut app,
                if attempt == 0 {
                    vec![]
                } else {
                    vec![key(Key::Enter, true)]
                }
            )
            .0
            .is_none()
        );
        let (_, output) = draw(&mut app, vec![]);
        let label = |name| {
            output
                .shapes
                .iter()
                .find_map(|shape| match &shape.shape {
                    egui::Shape::Text(text) if text.galley.job.text == name => {
                        Some(text.pos + text.galley.rect.center().to_vec2())
                    }
                    _ => None,
                })
                .unwrap_or_else(|| panic!("missing dialog label {name}"))
        };
        label("输入 VNC 密码");
        label("确定");
        label("取消");
        let field = ctx
            .memory(|memory| memory.focused())
            .expect("VNC password field focused");
        let field_rect = ctx.read_response(field).expect("password geometry").rect;
        assert!((field_rect.width() - 250.).abs() <= 1.);
        assert!((field_rect.height() - 23.).abs() <= 1.);
        draw(&mut app, vec![Event::Text("fixture".into())]);
        if attempt == 0 {
            assert!(draw(&mut app, vec![key(Key::Escape, true)]).0.is_none());
            wait(&app, Status::Failed("VNC 服务器需要密码".into()))?;
            assert!(matches!(peer_checkpoint()?, Peer::Cancelled));
        } else {
            assert!(draw(&mut app, vec![key(Key::Enter, true)]).0.is_none());
            draw(&mut app, vec![key(Key::Enter, false)]);
            if attempt == 2 {
                let pos = label("保存密码");
                for pressed in [true, false] {
                    draw(
                        &mut app,
                        vec![
                            Event::PointerMoved(pos),
                            Event::PointerButton {
                                pos,
                                pressed,
                                button: PointerButton::Primary,
                                modifiers: Modifiers::NONE,
                            },
                        ],
                    );
                }
            }
            assert!(matches!(
                draw(&mut app, vec![key(Key::Enter, true)]).0,
                Some(crate::panels::Intent::SubmitVncPassword)
            ));
            app.submit_vnc_password(&id);
            wait(&app, Status::Ready)?;
            assert!(matches!(peer_checkpoint()?, Peer::FirstFrameRequested));
        }
        assert!(!app.root_modal_open());
        assert!(egui::text_edit::TextEditState::load(&ctx, field).is_none());
        if attempt < 2 {
            assert_eq!(std::fs::read(&config)?, original);
        }
    }
    let saved = Store::load(&config)?;
    assert_eq!(saved.connections[0].text("password"), "fixture");
    assert!(saved.connections[0].flag("savePassword"));
    assert!(saved.connections[0].options["futureLegacy"]["preserved"] == true);
    app.close_tab(&id, true);
    app.runtime.as_ref().unwrap().block_on(async {
        tokio::time::timeout(Duration::from_secs(5), server).await???;
        Ok(())
    })
}

fn connection(mode: &str) -> anyhow::Result<Connection> {
    let socket = std::net::TcpListener::bind("127.0.0.1:0")?;
    let mut connection = Connection::new("RDP");
    connection.set("port", socket.local_addr()?.port());
    connection.set("username", "owned-fixture");
    connection.set("rdpOpenMode", mode);
    connection.set("mapClipboard", false);
    connection.set("enableSound", false);
    connection.set("futureLegacy", serde_json::json!({"preserved":true}));
    Ok(connection)
}

#[test]
fn rdp_temporary_password_survives_retry_in_both_modes_without_saving() -> anyhow::Result<()> {
    for mode in ["TAB", "WINDOW"] {
        let root = tempfile::tempdir()?;
        let path = root.path().join("connections.json");
        let saved = connection(mode)?;
        Store {
            connections: vec![saved.clone()],
            ..Default::default()
        }
        .save(&path)?;
        let before = std::fs::read(&path)?;
        let ctx = egui::Context::default();
        let runtime = tokio::runtime::Builder::new_multi_thread()
            .worker_threads(2)
            .enable_all()
            .build()?;
        let mut app =
            TomatoApp::with_repository(&ctx, runtime, ConnectionFileRepository::new(&path));
        app.open_connection(saved);
        let id = app.tabs.last().unwrap().id.clone();
        let Panel::NativeDesktop { view, .. } = &mut app.tabs.last_mut().unwrap().panel else {
            unreachable!()
        };
        view.password = "owned-temporary-password".into();
        view.remember = false;
        for _ in 0..2 {
            app.connect_desktop(&id);
            let Panel::NativeDesktop {
                connection,
                view,
                session,
                ..
            } = &app.tabs.last().unwrap().panel
            else {
                unreachable!()
            };
            assert_eq!(connection.text("password"), "owned-temporary-password");
            assert!(view.password.is_empty());
            assert!(session.is_some());
            assert!(app.store.connections[0].text("password").is_empty());
            assert_eq!(std::fs::read(&path)?, before);
        }
        assert!(
            Store::load(&path)?.connections[0]
                .options
                .contains_key("futureLegacy")
        );
    }
    Ok(())
}

#[test]
fn detached_rdp_failure_shows_the_cause_and_enter_repeat_cannot_resubmit() -> anyhow::Result<()> {
    let root = tempfile::tempdir()?;
    let ctx = egui::Context::default();
    let runtime = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(2)
        .enable_all()
        .build()?;
    let mut app = TomatoApp::with_repository(
        &ctx,
        runtime,
        ConnectionFileRepository::new(root.path().join("connections.json")),
    );
    let mut source = connection("WINDOW")?;
    source.set("password", "owned-secret");
    app.open_connection(source);
    let tab = app.tabs.last_mut().unwrap();
    let Panel::NativeDesktop {
        session: Some(session),
        ..
    } = &mut tab.panel
    else {
        unreachable!()
    };
    let deadline = Instant::now() + Duration::from_secs(5);
    loop {
        session.poll();
        if matches!(
            session.status(),
            tomato_services::remote_desktop::Status::Failed(_)
        ) {
            break;
        }
        anyhow::ensure!(Instant::now() < deadline, "Loopback rejection timed out");
        std::thread::sleep(Duration::from_millis(5));
    }
    let mut draw = |events| {
        let mut intent = None;
        let mut output = ctx.run_ui(
            egui::RawInput {
                screen_rect: Some(egui::Rect::from_min_size(
                    egui::Pos2::ZERO,
                    egui::vec2(1000., 700.),
                )),
                events,
                ..Default::default()
            },
            |ui| {
                intent = crate::panels::render_with_connections(ui, tab, &mut app.icons, &[]);
            },
        );
        output.textures_delta.clear();
        (intent, output)
    };
    let mut output = draw(vec![]).1;
    for _ in 0..3 {
        output = draw(vec![]).1;
    }
    assert!(output.shapes.iter().any(|shape|matches!(&shape.shape,egui::Shape::Text(text) if text.galley.job.text.contains("TCP connect"))));
    let field = ctx
        .memory(|memory| memory.focused())
        .expect("Password field must receive focus");
    let enter = |repeat| {
        vec![egui::Event::Key {
            key: egui::Key::Enter,
            physical_key: None,
            pressed: true,
            repeat,
            modifiers: Default::default(),
        }]
    };
    assert!(matches!(
        draw(enter(false)).0,
        Some(crate::panels::Intent::ConnectDesktop)
    ));
    ctx.memory_mut(|memory| memory.request_focus(field));
    assert!(draw(enter(true)).0.is_none());
    Ok(())
}
